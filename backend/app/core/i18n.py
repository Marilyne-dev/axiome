CATALOG: dict[str, dict[str, str]] = {"fr": _FR, "en": _EN}


def t(key: str, lang: str | None = None) -> str:
    """Traduit une clé. Repli : langue par défaut, puis la clé brute."""
    lang = lang or settings.default_lang
    return CATALOG.get(lang, {}).get(key) or CATALOG[settings.default_lang].get(key, key)
